-- Additive migration. Existing championships/matches are left unchanged.
-- Applied and verified on 2026-11-07.
BEGIN;
CREATE TABLE public.tournament_groups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  championship_id bigint NOT NULL REFERENCES public.championships(id) ON DELETE RESTRICT,
  sport_type public.sport_type NOT NULL,
  name text NOT NULL CHECK (name IN ('A', 'B')),
  finalized boolean NOT NULL DEFAULT false,
  qualification_order bigint[],
  UNIQUE (championship_id, sport_type, name)
);
CREATE TABLE public.tournament_group_teams (
  group_id bigint NOT NULL REFERENCES public.tournament_groups(id) ON DELETE CASCADE,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE RESTRICT,
  PRIMARY KEY (group_id, team_id)
);
ALTER TABLE public.matches ADD COLUMN group_id bigint REFERENCES public.tournament_groups(id) ON DELETE RESTRICT;
CREATE INDEX matches_group_id_idx ON public.matches(group_id);
ALTER TABLE public.tournament_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tournament_group_teams ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.tournament_groups, public.tournament_group_teams TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.tournament_groups_id_seq TO service_role;

-- Serialize draws per championship and create all six fixtures atomically.
CREATE FUNCTION public.create_boys_groups(p_championship bigint, p_sport public.sport_type,
  p_a bigint[], p_b bigint[]) RETURNS void LANGUAGE plpgsql SET search_path = public AS $$
DECLARE group_key bigint; members bigint[]; label text; i int; j int;
BEGIN
  PERFORM id FROM championships WHERE id = p_championship AND status = 'ongoing' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Choose an ongoing championship.'; END IF;
  IF array_length(p_a, 1) IS DISTINCT FROM 3 OR array_length(p_b, 1) IS DISTINCT FROM 3 OR
    (SELECT count(DISTINCT x) FROM unnest(p_a || p_b) x) <> 6 OR
    (SELECT count(*) FROM teams WHERE id = ANY(p_a || p_b) AND championship_id = p_championship AND gender = 'male') <> 6
    THEN RAISE EXCEPTION 'Choose six different boys teams, three per group.'; END IF;
  IF EXISTS (SELECT 1 FROM matches WHERE championship_id = p_championship AND sport_type = p_sport AND gender = 'male') OR
    EXISTS (SELECT 1 FROM tournament_groups WHERE championship_id = p_championship AND sport_type = p_sport)
    THEN RAISE EXCEPTION 'This sport already has boys fixtures. Existing fixtures are preserved; use a new championship for the group format.'; END IF;
  FOREACH label IN ARRAY ARRAY['A','B'] LOOP
    members := CASE WHEN label = 'A' THEN p_a ELSE p_b END;
    INSERT INTO tournament_groups(championship_id,sport_type,name) VALUES(p_championship,p_sport,label) RETURNING id INTO group_key;
    INSERT INTO tournament_group_teams(group_id,team_id) SELECT group_key, unnest(members);
    FOR i IN 1..2 LOOP FOR j IN (i+1)..3 LOOP
      INSERT INTO matches(championship_id,sport_type,gender,group_id,team_a_id,team_b_id,status)
      VALUES(p_championship,p_sport,'male',group_key,members[i],members[j],'not_yet_scheduled');
    END LOOP; END LOOP;
  END LOOP;
END $$;

-- A snapshot prevents qualifying teams from a table that changed during review.
CREATE FUNCTION public.finalize_boys_groups(p_championship bigint, p_sport public.sport_type,
  p_seeds bigint[], p_snapshot jsonb) RETURNS void LANGUAGE plpgsql SET search_path = public AS $$
DECLARE final_id bigint; current_snapshot jsonb;
BEGIN
  PERFORM id FROM championships WHERE id=p_championship AND status='ongoing' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Choose an ongoing championship.'; END IF;
  PERFORM id FROM tournament_groups WHERE championship_id=p_championship AND sport_type=p_sport FOR UPDATE;
  IF (SELECT count(*) FROM tournament_groups WHERE championship_id=p_championship AND sport_type=p_sport AND NOT finalized) <> 2
    THEN RAISE EXCEPTION 'The group stage is missing or already finalized.'; END IF;
  PERFORM m.id FROM matches m JOIN tournament_groups g ON g.id=m.group_id
    WHERE g.championship_id=p_championship AND g.sport_type=p_sport FOR UPDATE OF m;
  SELECT jsonb_agg(jsonb_build_object('id',m.id,'status',m.status,'winner_id',m.winner_id,
    'team_a_score',m.team_a_score,'team_b_score',m.team_b_score) ORDER BY m.id) INTO current_snapshot
    FROM matches m JOIN tournament_groups g ON g.id=m.group_id WHERE g.championship_id=p_championship AND g.sport_type=p_sport;
  IF current_snapshot IS DISTINCT FROM p_snapshot OR jsonb_array_length(current_snapshot) <> 6 OR
    EXISTS (SELECT 1 FROM matches m JOIN tournament_groups g ON g.id=m.group_id WHERE g.championship_id=p_championship
      AND g.sport_type=p_sport AND (m.status <> 'played' OR m.winner_id IS NULL))
    THEN RAISE EXCEPTION 'Results changed or are incomplete. Refresh the standings before finalizing.'; END IF;
  IF array_length(p_seeds,1) IS DISTINCT FROM 4 OR (SELECT count(DISTINCT x) FROM unnest(p_seeds) x) <> 4 OR
    (SELECT count(*) FROM tournament_group_teams t JOIN tournament_groups g ON g.id=t.group_id
      WHERE g.championship_id=p_championship AND g.sport_type=p_sport AND
        ((g.name='A' AND t.team_id=ANY(ARRAY[p_seeds[1],p_seeds[4]])) OR
         (g.name='B' AND t.team_id=ANY(ARRAY[p_seeds[2],p_seeds[3]])))) <> 4
    THEN RAISE EXCEPTION 'Invalid semifinal seeds.'; END IF;
  INSERT INTO matches(championship_id,sport_type,gender,boys_stage_groups,status)
    VALUES(p_championship,p_sport,'male','finals','not_yet_scheduled') RETURNING id INTO final_id;
  INSERT INTO matches(championship_id,sport_type,gender,boys_stage_groups,status,team_a_id,team_b_id,next_match_id)
    VALUES(p_championship,p_sport,'male','semi-finals','not_yet_scheduled',p_seeds[1],p_seeds[2],final_id),
          (p_championship,p_sport,'male','semi-finals','not_yet_scheduled',p_seeds[3],p_seeds[4],final_id);
  UPDATE tournament_groups g SET finalized=true,
    qualification_order=CASE WHEN name='A' THEN ARRAY[p_seeds[1],p_seeds[4]] ELSE ARRAY[p_seeds[3],p_seeds[2]] END ||
      ARRAY(SELECT team_id FROM tournament_group_teams WHERE group_id=g.id AND NOT team_id=ANY(p_seeds))
    WHERE championship_id=p_championship AND sport_type=p_sport;
END $$;

CREATE FUNCTION public.guard_finalized_group_results() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF EXISTS(SELECT 1 FROM tournament_groups WHERE id=OLD.group_id AND finalized) THEN
    RAISE EXCEPTION 'Group stage finalized. Its results are locked to preserve knockout qualification.';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER guard_finalized_group_results BEFORE UPDATE OR DELETE ON public.matches
  FOR EACH ROW WHEN (OLD.group_id IS NOT NULL) EXECUTE FUNCTION public.guard_finalized_group_results();
REVOKE ALL ON FUNCTION public.create_boys_groups(bigint,public.sport_type,bigint[],bigint[]) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.finalize_boys_groups(bigint,public.sport_type,bigint[],jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.create_boys_groups(bigint,public.sport_type,bigint[],bigint[]) TO service_role;
GRANT EXECUTE ON FUNCTION public.finalize_boys_groups(bigint,public.sport_type,bigint[],jsonb) TO service_role;
NOTIFY pgrst, 'reload schema';
COMMIT;
