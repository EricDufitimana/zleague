-- Families become editable data instead of a Postgres enum.
--
-- Renaming a family used to mean ALTER TYPE ... RENAME VALUE, which an app
-- cannot do at runtime. This moves the list into a families table, converts the
-- two columns that used the enum to text, and wires them back with foreign keys
-- that CASCADE on update - so renaming a family in the dashboard rewrites every
-- team and player row that referenced it, atomically.
--
-- The public.family_type enum is intentionally left in place but unused; it is
-- kept so this migration stays reversible.

BEGIN;

CREATE TABLE IF NOT EXISTS public.families (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text          NOT NULL UNIQUE,
  grade       public.grade  NOT NULL,
  gender      public.gender NOT NULL,
  is_active   boolean       NOT NULL DEFAULT true,
  sort_order  integer       NOT NULL DEFAULT 0,
  created_at  timestamptz   NOT NULL DEFAULT now(),
  updated_at  timestamptz   NOT NULL DEFAULT now(),
  CONSTRAINT families_name_not_blank CHECK (length(btrim(name)) > 0)
);

-- Matches every other table in this schema; all access goes through
-- service-role API routes, so no anon policies are granted.
ALTER TABLE public.families ENABLE ROW LEVEL SECURITY;

