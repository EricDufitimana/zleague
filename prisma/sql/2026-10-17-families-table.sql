-- The enum columns become text so arbitrary names are possible.
ALTER TABLE public.teams   ALTER COLUMN name   TYPE text USING name::text;
ALTER TABLE public.players ALTER COLUMN family TYPE text USING family::text;

-- Referential integrity, with renames cascading outward.
-- Deletes are left to fail on purpose: a family still used by a team or player
-- must be deactivated (is_active = false), not removed.
ALTER TABLE public.teams
  ADD CONSTRAINT teams_name_families_fkey
  FOREIGN KEY (name) REFERENCES public.families (name)
  ON UPDATE CASCADE ON DELETE RESTRICT;

ALTER TABLE public.players
  ADD CONSTRAINT players_family_families_fkey
  FOREIGN KEY (family) REFERENCES public.families (name)
  ON UPDATE CASCADE ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS teams_name_idx   ON public.teams (name);
CREATE INDEX IF NOT EXISTS players_family_idx ON public.players (family);

